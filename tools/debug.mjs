import { chromium } from 'playwright';
const OUT = process.argv[2];
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text()); });
await page.goto('http://localhost:2567/');
await page.waitForTimeout(800);
await page.click('#bPrivate');
await page.waitForSelector('#lobby.show');
await page.click('#bReady');
await page.waitForFunction(() => window.__doors?.inGame, null, { timeout: 60000 });
await page.waitForTimeout(2000);
const info = await page.evaluate(() => { const g = __doors.game; return { self: !!g.self, snared: g.self?.snared, hidden: g.self?.hidden, phys: g.physics.ready, modal: g.ui.modalOpen, enabled: g.input.enabled, touch: g.input.touch }; });
console.log(JSON.stringify(info));
await page.keyboard.down('KeyW');
await page.waitForTimeout(300);
console.log(await page.evaluate(() => JSON.stringify({ mv: __doors.game.input.moveY, keys: [...__doors.game.input.keys], pos: __doors.pos })));
await page.waitForTimeout(2000);
await page.keyboard.up('KeyW');
console.log(await page.evaluate(() => JSON.stringify({ pos: __doors.pos, room: __doors.room })));
await page.screenshot({ path: OUT + '/05.png' });
await browser.close();
